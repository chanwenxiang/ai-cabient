import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { networkInterfaces } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envFiles = [
  join(root, 'clients/consumer-mp/.env.development'),
  join(root, 'clients/merchant-mp/.env.development')
];

function pickLanIp() {
  const candidates = [];
  const nets = networkInterfaces();
  for (const name of Object.keys(nets)) {
    for (const net of nets[name] || []) {
      if (net.family !== 'IPv4' || net.internal) continue;
      if (/^(192\.168\.|10\.)/.test(net.address)) candidates.push(net.address);
    }
  }
  const preferred = candidates.find((ip) => /^192\.168\.(0|1)\./.test(ip));
  return preferred || candidates[0] || '';
}

function probe(base) {
  try {
    execSync(
      `powershell -NoProfile -Command "Invoke-RestMethod -Uri '${base}/api/v2/auth/server-boot' -TimeoutSec 2 | Out-Null"`,
      { stdio: 'ignore' }
    );
    return true;
  } catch {
    return false;
  }
}

/**
 * 选择顺序：
 * 1. 显式 `MP_API_BASE_URL` / `VITE_API_BASE_URL`
 * 2. 环回（微信开发者工具模拟器本机）
 * 3. 可达的局域网 IP（真机预览；探测失败则不用，禁止写死超时 IP）
 */
const explicit = String(process.env.MP_API_BASE_URL || process.env.VITE_API_BASE_URL || '')
  .trim()
  .replace(/\/$/, '');

const loopbackCandidates = [
  'http://127.0.0.1',
  'http://localhost',
  'http://127.0.0.1:18080',
  'http://localhost:18080'
];

const lanIp = pickLanIp();
const lanCandidates = lanIp
  ? [`http://${lanIp}`, `http://${lanIp}:18080`, `http://${lanIp}:8080`]
  : [];

const forceLan = String(process.env.MP_API_USE_LAN || '').trim() === '1';
const ordered = explicit
  ? [explicit]
  : forceLan
    ? [...lanCandidates, ...loopbackCandidates]
    : [...loopbackCandidates, ...lanCandidates];

let base = 'http://127.0.0.1';
let reachable = false;
for (const url of ordered) {
  if (probe(url)) {
    base = url;
    reachable = true;
    break;
  }
}
if (!reachable) {
  console.warn(
    `trade-service/gateway not reachable at ${ordered.join(' | ')} — fallback ${base}; start backend first`
  );
}

const body = `# Auto-generated by scripts/sync-consumer-mp-api.mjs\nVITE_API_BASE_URL=${base}\n`;
for (const envFile of envFiles) {
  writeFileSync(envFile, body, 'utf8');
}
console.log(`mini-program API => ${base}${reachable ? '' : ' (unreachable fallback)'}`);
