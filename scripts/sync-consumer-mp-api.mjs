import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { networkInterfaces } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envFiles = [
  join(root, 'clients/consumer-mp/.env.development'),
  join(root, 'clients/merchant-mp/.env.development')
];

function pickLanIp() {
  const candidates = [];
  const nets = networkInterfaces();
  for (const name of Object.keys(nets)) {
    for (const net of nets[name] || []) {
      if (net.family !== 'IPv4' || net.internal) continue;
      if (/^(192\.168\.|10\.)/.test(net.address)) candidates.push(net.address);
    }
  }
  const preferred = candidates.find((ip) => /^192\.168\.(0|1)\./.test(ip));
  return preferred || candidates[0] || '127.0.0.1';
}

function probe(base) {
  try {
    execSync(
      `powershell -NoProfile -Command "Invoke-RestMethod -Uri '${base}/api/v2/auth/server-boot' -TimeoutSec 2 | Out-Null"`,
      { stdio: 'ignore' }
    );
    return true;
  } catch {
    return false;
  }
}

const ip = pickLanIp();
// Prefer gateway :80 (win-ports full stack), then trade host map :18080, then container-local :8080
const candidates = [`http://${ip}`, `http://${ip}:18080`, `http://${ip}:8080`];
let base = candidates[0];
let reachable = false;
for (const url of candidates) {
  if (probe(url)) {
    base = url;
    reachable = true;
    break;
  }
}
if (!reachable) {
  console.warn(
    `trade-service/gateway not reachable at ${candidates.join(' | ')} — start backend first`
  );
  base = candidates[0];
}

const body = `# Auto-generated by scripts/sync-consumer-mp-api.mjs\nVITE_API_BASE_URL=${base}\n`;
for (const envFile of envFiles) {
  writeFileSync(envFile, body, 'utf8');
}
console.log(`mini-program API => ${base}`);
