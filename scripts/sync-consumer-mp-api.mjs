import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { networkInterfaces } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = join(root, 'clients/consumer-mp/.env.development');

function pickLanIp() {
  const candidates = [];
  const nets = networkInterfaces();
  for (const name of Object.keys(nets)) {
    for (const net of nets[name] || []) {
      if (net.family !== 'IPv4' || net.internal) continue;
      if (/^(192\.168\.|10\.)/.test(net.address)) candidates.push(net.address);
    }
  }
  const preferred = candidates.find((ip) => /^192\.168\.(0|1)\./.test(ip));
  return preferred || candidates[0] || '127.0.0.1';
}

const ip = pickLanIp();
const base = `http://${ip}:8080`;
try {
  execSync(`powershell -NoProfile -Command "Invoke-RestMethod -Uri '${base}/api/v2/auth/server-boot' -TimeoutSec 2 | Out-Null"`, {
    stdio: 'ignore'
  });
} catch {
  console.warn(`trade-service not reachable at ${base} — start backend first`);
}

writeFileSync(
  envFile,
  `# Auto-generated by scripts/sync-consumer-mp-api.mjs\nVITE_API_BASE_URL=${base}\n`,
  'utf8'
);
console.log(`consumer-mp API => ${base}`);
