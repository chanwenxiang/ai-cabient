def load_catalog_mapping() -> None:
    """从 trade internal API 加载 sku_id ↔ yolo_class_name；失败时用内置 demo 映射。"""
    global CLASSES, SKU_TO_CLASS, CLASS_SOURCES
    rows: list[tuple[str, str, str]] = []
    try:
        sys.path.insert(0, str(ROOT))
        from app.recognition.mapping_client import fetch_catalog_classes

        rows = fetch_catalog_classes()
    except Exception as exc:
        print(f"warn: catalog import failed: {exc}", file=sys.stderr)

    if not rows:
        try:
            import httpx
            import os

            base = os.getenv("TRADE_SERVICE_URL", "http://localhost:8080").rstrip("/")
            key = os.getenv("INTERNAL_API_KEY", "dev-internal-key-change-me")
            with httpx.Client(timeout=5.0) as client:
                resp = client.get(
                    f"{base}/internal/v1/vision/catalog-classes",
                    headers={"X-Internal-Api-Key": key},
                )
                resp.raise_for_status()
                data = resp.json().get("data") or []
            rows = [
                (str(r["skuId"]), str(r["className"]), str(r.get("skuName") or ""))
                for r in data
                if r.get("skuId") and r.get("className")
            ]
        except Exception as exc:
            print(f"warn: catalog HTTP failed: {exc}", file=sys.stderr)

    if rows:
        seen: dict[str, int] = {}
        classes: list[str] = []
        sku_map: dict[str, int] = {}
        for sku_id, class_name, _ in rows:
            if class_name not in seen:
                seen[class_name] = len(classes)
                classes.append(class_name)
            sku_map[sku_id] = seen[class_name]
        CLASSES = classes
        SKU_TO_CLASS = sku_map
        print(f"catalog classes loaded: {len(CLASSES)} classes, {len(SKU_TO_CLASS)} skus")
    else:
        CLASSES = list(_FALLBACK_CLASSES)
        SKU_TO_CLASS = dict(_FALLBACK_SKU_TO_CLASS)
        print("using fallback demo class mapping", file=sys.stderr)

    CLASS_SOURCES = _build_class_sources()


def _build_class_sources() -> dict[int, list[Path]]:
    """按 class 名启发式匹配 consumer-mp 静态图与 testdata。"""
    static_dir = REPO / "clients/consumer-mp/src/static/sku"
    testdata = REPO / "testdata"
    name_hints: dict[str, list[str]] = {
        "cola": ["cola"],
        "sprite": ["sprite", "soda"],
        "water": ["water"],
        "chips": ["chips", "snack"],
        "milk": ["milk"],
        "noodle": ["noodle"],
    }
    sources: dict[int, list[Path]] = {i: [] for i in range(len(CLASSES))}
    for idx, cls in enumerate(CLASSES):
        paths: list[Path] = []
        for hint_key, hints in name_hints.items():
            if hint_key in cls.lower() or any(h in cls.lower() for h in hints):
                for p in static_dir.glob("*.png"):
                    if any(h in p.stem.lower() for h in hints):
                        paths.append(p)
        for p in testdata.glob("*"):
            if p.is_file() and any(h in cls.lower() for h in (cls.split("_") + [cls[:4]])):
                paths.append(p)
        if not paths and static_dir.exists():
            pngs = sorted(static_dir.glob("*.png"))
            if idx < len(pngs):
                paths.append(pngs[idx])
        sources[idx] = paths
    return sources


def write_training_data_yaml() -> None:
    """根据 CLASSES 重写 training/data.yaml。"""
    yaml_path = ROOT / "training" / "data.yaml"
    names_block = "\n".join(f"  {i}: {name}" for i, name in enumerate(CLASSES))
    content = (
        "# Auto-generated by collect_sku_dataset.py — do not hand-edit class list\n"
        f"path: {DATASET.as_posix()}\n"
        "train: images/train\n"
        "val: images/val\n"
        "test: images/test\n"
        f"nc: {len(CLASSES)}\n"
        "names:\n"
        f"{names_block}\n"
    )
    yaml_path.write_text(content, encoding="utf-8")
    print(f"wrote {yaml_path} nc={len(CLASSES)}")



@dataclass
class Box:
    cls: int
    cx: float
    cy: float
    w: float
    h: float

    def yolo_line(self) -> str:
        return f"{self.cls} {self.cx:.6f} {self.cy:.6f} {self.w:.6f} {self.h:.6f}"


def _import_cv():
    try:
        import cv2  # type: ignore
        import numpy as np  # type: ignore
        return cv2, np
    except ImportError as exc:
        print("pip install opencv-python-headless numpy pillow", file=sys.stderr)
        raise SystemExit(1) from exc


def load_rgba(path: Path, cv2, np):
    from PIL import Image

    if not path.exists():
        return None
    if path.suffix.lower() in {".png", ".webp"}:
        pil = Image.open(path).convert("RGBA")
        arr = np.array(pil)
        return cv2.cvtColor(arr, cv2.COLOR_RGBA2BGRA)
    img = cv2.imread(str(path), cv2.IMREAD_UNCHANGED)
    if img is None:
        pil = Image.open(path).convert("RGB")
        img = cv2.cvtColor(np.array(pil), cv2.COLOR_RGB2BGR)
    return img


def shelf_background(w: int, h: int, cv2, np, variant: int = 0) -> "np.ndarray":
    base = np.full((h, w, 3), 28 + variant * 3, dtype=np.uint8)
    for y in range(h):
        shade = int(35 + (y / max(h - 1, 1)) * 45 + variant * 2)
        base[y, :, :] = (shade, shade + 5, shade + 8)
    # 货架横条
    for row in range(2, 5):
        y = int(h * row / 5)
        cv2.rectangle(base, (0, y - 2), (w, y + 2), (55, 58, 62), -1)
    if variant % 3 == 1:
        cv2.rectangle(base, (10, 10), (w - 10, h - 10), (40, 42, 46), 2)
    return base


def paste_product(bg, product_bgra, cv2, np, rng: random.Random) -> Box | None:
    if product_bgra is None:
        return None
    h, w = bg.shape[:2]
    if product_bgra.shape[2] == 4:
        prod = product_bgra
    else:
        prod = cv2.cvtColor(product_bgra, cv2.COLOR_BGR2BGRA)

    scale = rng.uniform(0.22, 0.55)
    target_w = max(int(w * scale), 40)
    aspect = prod.shape[0] / max(prod.shape[1], 1)
    target_h = max(int(target_w * aspect), 40)
    prod = cv2.resize(prod, (target_w, target_h), interpolation=cv2.INTER_AREA)

    if rng.random() < 0.5:
        prod = cv2.flip(prod, 1)

    x1 = rng.randint(20, max(21, w - target_w - 20))
    y1 = rng.randint(int(h * 0.15), max(int(h * 0.15) + 1, h - target_h - 30))

    alpha = prod[:, :, 3:4].astype(float) / 255.0
    rgb = prod[:, :, :3].astype(float)
    roi = bg[y1 : y1 + target_h, x1 : x1 + target_w].astype(float)
    blended = roi * (1 - alpha) + rgb * alpha
    bg[y1 : y1 + target_h, x1 : x1 + target_w] = blended.astype(np.uint8)

    cx = (x1 + target_w / 2) / w
    cy = (y1 + target_h / 2) / h
    bw = target_w / w
    bh = target_h / h
    return Box(cls=-1, cx=cx, cy=cy, w=bw, bh=bh)


def augment(img, cv2, np, rng: random.Random):
    out = img.copy()
    if rng.random() < 0.6:
        factor = rng.uniform(0.75, 1.25)
        out = np.clip(out.astype(float) * factor, 0, 255).astype(np.uint8)
    if rng.random() < 0.3:
        k = rng.choice([3, 5])
        out = cv2.GaussianBlur(out, (k, k), 0)
    if rng.random() < 0.25:
        noise = rng.randint(-12, 12, out.shape, dtype=np.int16)
        out = np.clip(out.astype(np.int16) + noise, 0, 255).astype(np.uint8)
    return out


def write_sample(split: str, stem: str, img, boxes: list[Box], cv2) -> None:
    img_dir = DATASET / "images" / split
    lbl_dir = DATASET / "labels" / split
    img_dir.mkdir(parents=True, exist_ok=True)
    lbl_dir.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(img_dir / f"{stem}.jpg"), img, [int(cv2.IMWRITE_JPEG_QUALITY), rng_quality()])
    lines = [b.yolo_line() for b in boxes if b.cls >= 0]
    (lbl_dir / f"{stem}.txt").write_text("\n".join(lines) + ("\n" if lines else ""), encoding="utf-8")


def rng_quality() -> int:
    return random.randint(82, 95)


def bootstrap_synthetic(per_class: int, cv2, np, rng: random.Random) -> dict[str, int]:
    counts: dict[str, int] = {c: 0 for c in CLASSES}
    splits = {"train": 0.70, "val": 0.15, "test": 0.15}
    w, h = 640, 480

    for cls_idx, class_name in enumerate(CLASSES):
        sources = [p for p in CLASS_SOURCES.get(cls_idx, []) if p.exists()]
        if not sources:
            print(f"warn: no source image for {class_name}", file=sys.stderr)
            continue

        for i in range(per_class):
            split = "train" if i < int(per_class * splits["train"]) else (
                "val" if i < int(per_class * (splits["train"] + splits["val"])) else "test"
            )
            bg = shelf_background(w, h, cv2, np, variant=i % 7)
            n_items = 1 if rng.random() < 0.75 else rng.randint(2, 3)
            boxes: list[Box] = []
            for _ in range(n_items):
                src = rng.choice(sources)
                prod = load_rgba(src, cv2, np)
                box = paste_product(bg, prod, cv2, np, rng)
                if box:
                    box.cls = cls_idx
                    boxes.append(box)
            if rng.random() < 0.15:
                # 空柜负样本（无标注）
                boxes = []
            bg = augment(bg, cv2, np, rng)
            stem = f"syn_{class_name}_{i:04d}"
            write_sample(split, stem, bg, boxes, cv2)
            counts[class_name] += 1

    return counts


def download_minio_raw() -> list[Path]:
    """通过 docker mc 拉取 MinIO 会话 TOP 图到 raw/minio/。"""
    out_dir = RAW / "minio"
    out_dir.mkdir(parents=True, exist_ok=True)
    prefix = "local/cabinet-videos/sim/"
    script = (
        "mc alias set local http://localhost:9000 minioadmin minioadmin >/dev/null 2>&1; "
        f"mc find local/cabinet-videos --name '*-top.jpg' --print '{{{{.Key}}}}'"
    )
    try:
        keys = subprocess.check_output(
            ["docker", "exec", "ai-cabinet-minio-1", "sh", "-c", script],
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip().splitlines()
    except subprocess.CalledProcessError:
        print("warn: minio download skipped (container or mc unavailable)", file=sys.stderr)
        return []

    saved: list[Path] = []
    for key in keys:
        if not key.strip():
            continue
        name = Path(key).name
        dest = out_dir / name
        if dest.exists():
            saved.append(dest)
            continue
        cp = (
            f"mc alias set local http://localhost:9000 minioadmin minioadmin >/dev/null 2>&1; "
            f"mc cp 'local/{key}' '/tmp/{name}'"
        )
        try:
            subprocess.check_call(["docker", "exec", "ai-cabinet-minio-1", "sh", "-c", cp], stderr=subprocess.DEVNULL)
            subprocess.check_call(["docker", "cp", f"ai-cabinet-minio-1:/tmp/{name}", str(dest)])
            saved.append(dest)
        except subprocess.CalledProcessError:
            print(f"warn: failed copy {key}", file=sys.stderr)
    print(f"minio raw images: {len(saved)}")
    return saved


def query_session_skus() -> dict[str, str]:
    """session_id -> sku_id（有订单行的会话）。"""
    sql = """
    SELECT DISTINCT s.session_id, ol.sku_id
    FROM shopping_session s
    JOIN cabinet_order o ON o.session_id = s.session_id
    JOIN cabinet_order_line ol ON ol.order_id = o.order_id
    WHERE s.video_uri IS NOT NULL;
    """
    try:
        out = subprocess.check_output(
            [
                "docker", "exec", "ai-cabinet-postgres-1",
                "psql", "-U", "aicabinet", "-d", "aicabinet", "-t", "-A", "-F", "|", "-c", sql,
            ],
            text=True,
            stderr=subprocess.DEVNULL,
        )
    except subprocess.CalledProcessError:
        return {}

    mapping: dict[str, str] = {}
    for line in out.strip().splitlines():
        parts = line.strip().split("|")
        if len(parts) >= 2:
            mapping[parts[0].strip()] = parts[1].strip()
    return mapping


def ingest_minio_labeled(session_skus: dict[str, str], cv2, np, rng: random.Random) -> dict[str, int]:
    counts: dict[str, int] = {c: 0 for c in CLASSES}
    files = sorted((RAW / "minio").glob("*.jpg"))
    if not files:
        return counts

    for idx, path in enumerate(files):
        m = re.match(r"^([A-F0-9]+)-top\.jpg$", path.name, re.I)
        session_id = m.group(1) if m else path.stem
        sku = session_skus.get(session_id, "")
        cls_idx = SKU_TO_CLASS.get(sku)
        if cls_idx is None:
            # 启发式：大图 soda，小图 bottle/cola
            cls_idx = 1 if path.stat().st_size > 500_000 else 0

        img = cv2.imread(str(path))
        if img is None:
            continue
        img = cv2.resize(img, (640, 480))
        img = augment(img, cv2, np, rng)
        split = "train" if idx % 5 else ("val" if idx % 5 == 1 else "test")
        # 模拟器图：商品占画面主体
        box = Box(cls=cls_idx, cx=0.5, cy=0.52, w=0.78, h=0.82)
        stem = f"minio_{session_id[:12]}_{idx:03d}"
        write_sample(split, stem, img, [box], cv2)
        counts[CLASSES[cls_idx]] += 1
    return counts


def write_meta(counts: dict) -> None:
    META.mkdir(parents=True, exist_ok=True)
    guide = META / "labeling-guide.md"
    guide.write_text(
        "# cabinet-skus-v1 采集说明\n\n"
        "本数据集由 `scripts/collect_sku_dataset.py` 自动生成：\n\n"
        "1. **MinIO 会话图**：来自 device-simulator 上传的真实购物会话 TOP 帧\n"
        "2. **合成柜内图**：基于 `consumer-mp/src/static/sku/*.png` 贴图到货架背景\n"
        "3. **标注**：合成图 bbox 为已知贴图位置；MinIO 图为全幅商品启发式框\n\n"
        "生产上线前请用真实柜内多场景照片逐步替换合成样本，并人工复核 bbox。\n",
        encoding="utf-8",
    )
    (META / "collection-stats.json").write_text(
        json.dumps(counts, ensure_ascii=False, indent=2), encoding="utf-8"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Collect cabinet SKU YOLO dataset")
    parser.add_argument("--per-class", type=int, default=70, help="Synthetic images per class")
    parser.add_argument("--minio", action="store_true", default=True, help="Download MinIO session images")
    parser.add_argument("--no-minio", action="store_false", dest="minio")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    cv2, np = _import_cv()
    rng = random.Random(args.seed)

    load_catalog_mapping()
    write_training_data_yaml()

    # 清空旧 images/labels（保留 raw）
    for sub in ("train", "val", "test"):
        for kind in ("images", "labels"):
            d = DATASET / kind / sub
            if d.exists():
                shutil.rmtree(d)

    stats: dict = {"synthetic": {}, "minio": {}}

    print(f"=== bootstrap synthetic ({args.per_class}/class) ===")
    stats["synthetic"] = bootstrap_synthetic(args.per_class, cv2, np, rng)

    if args.minio:
        print("=== download MinIO session images ===")
        download_minio_raw()
        session_skus = query_session_skus()
        print(f"session sku mappings: {len(session_skus)}")
        print("=== ingest MinIO with labels ===")
        stats["minio"] = ingest_minio_labeled(session_skus, cv2, np, rng)

    write_meta(stats)
    total = sum(len(list((DATASET / "images" / s).glob("*.jpg"))) for s in ("train", "val", "test"))
    print(f"=== done: {total} images under {DATASET} ===")
    print(json.dumps(stats, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
